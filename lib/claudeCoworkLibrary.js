export const CLAUDE_COWORK_PACKAGES = CLAUDE_COWORK_LIBRARY.packages;
export const CLAUDE_COWORK_SKILLS = CLAUDE_COWORK_LIBRARY.skills;
export const CLAUDE_COWORK_SELECTION_GUIDES = CLAUDE_COWORK_LIBRARY.selectionGuides;

export function getClaudeCoworkSkill(slug) {
  return CLAUDE_COWORK_SKILLS.find((skill) => skill.id === slug);
}

export function getClaudeCoworkPackage(slug) {
  return CLAUDE_COWORK_PACKAGES.find((pack) => pack.id === slug);
}

export function getClaudeCoworkSkillsForPackage(packageId) {
  const pack = getClaudeCoworkPackage(packageId);
  if (!pack) return [];
  return pack.skillIds.map((id) => getClaudeCoworkSkill(id)).filter(Boolean);
}

export function getClaudeCoworkPackagesForSkill(skill) {
  return (skill?.packageIds || []).map((id) => getClaudeCoworkPackage(id)).filter(Boolean);
}
